#!/usr/bin/env bash
# Build autograder.zip for a Gradescope Programming Assignment.
# Run tools/build-autograder.js FIRST to bundle course.json + banks into source/.
#
# SECRETS: Gradescope has no secrets manager — whatever the container needs must be
# inside the image. So autograder.zip DOES contain your signing secret and (if you
# use it) your GenAI key. Two ways to supply them:
#
#   A) environment (preferred — nothing secret is left on disk afterwards):
#        ORALSCALE_SECRET=$(node ../tools/make-config.js --print) \
#        GENAI_STUDIO_API_KEY=sk-... bash build.sh
#      secret.env is written into the zip and then deleted.
#
#   B) a persistent source/secret.env file (gitignored). Convenient, but it sits in
#      your working tree in plaintext; chmod 600 it.
#
# Either way, treat autograder.zip as a secret artifact: do not email it, put it in
# a shared drive, or commit it. Anyone who can read it can forge certificates.
set -euo pipefail
cd "$(dirname "$0")"

if [ ! -f source/course.json ]; then
  echo "source/course.json missing. Run first:  node ../tools/build-autograder.js courses/<id>/course.json"
  exit 1
fi

EPHEMERAL=0
if [ ! -f source/secret.env ] && [ -n "${ORALSCALE_SECRET:-}" ]; then
  echo "Composing source/secret.env from the environment (it will be removed after packaging)."
  umask 077
  {
    echo "# Generated by build.sh from the environment. Do not commit."
    echo "ORALSCALE_SECRET=${ORALSCALE_SECRET}"
    [ -n "${ORALSCALE_ASSIGNMENT:-}" ] && echo "ORALSCALE_ASSIGNMENT=${ORALSCALE_ASSIGNMENT}"
    [ -n "${ORALSCALE_WEBAPP_URL:-}" ] && echo "ORALSCALE_WEBAPP_URL=${ORALSCALE_WEBAPP_URL}"
    echo "ORALSCALE_MAX_POINTS=${ORALSCALE_MAX_POINTS:-10}"
    [ -n "${GENAI_STUDIO_API_KEY:-}" ]  && echo "GENAI_STUDIO_API_KEY=${GENAI_STUDIO_API_KEY}"
    [ -n "${GENAI_STUDIO_BASE_URL:-}" ] && echo "GENAI_STUDIO_BASE_URL=${GENAI_STUDIO_BASE_URL}"
    [ -n "${GENAI_STUDIO_MODEL:-}" ]    && echo "GENAI_STUDIO_MODEL=${GENAI_STUDIO_MODEL}"
    # Which local grading model the image should bake in. setup.sh reads this at
    # BUILD time, so it has to be in the zip before the image is built — not just
    # in course.json, which is only read at grading time.
    [ -n "${ORALSCALE_LOCAL_MODEL_KEY:-}" ] && echo "ORALSCALE_LOCAL_MODEL_KEY=${ORALSCALE_LOCAL_MODEL_KEY}"
    [ -n "${ORALSCALE_SKIP_LOCAL_LLM:-}" ]  && echo "ORALSCALE_SKIP_LOCAL_LLM=${ORALSCALE_SKIP_LOCAL_LLM}"
    # Whether this course actually GRADES with the local model, as opposed to
    # keeping it as an outage fallback. Decides whether setup.sh treats an
    # unbuildable local runtime as fatal or as a warning: for a genai course,
    # failing the image build over an unused fallback would leave the instructor
    # with no autograder at all.
    echo "ORALSCALE_LOCAL_REQUIRED=${ORALSCALE_LOCAL_REQUIRED:-0}"
  } > source/secret.env
  EPHEMERAL=1
fi

if [ ! -f source/secret.env ]; then
  echo "ERROR: no source/secret.env and no ORALSCALE_SECRET in the environment."
  echo "  Either:  ORALSCALE_SECRET=\$(node ../tools/make-config.js --print) bash build.sh"
  echo "  Or:      cp source/secret.env.example source/secret.env  && edit it"
  exit 1
fi

# Catch the mistakes that produce a class-wide zero on the first real submission.
if grep -qE '^ORALSCALE_SECRET=(your-signing-secret-here)?$' source/secret.env; then
  echo "ERROR: ORALSCALE_SECRET in source/secret.env is empty or still the placeholder."
  exit 1
fi
if grep -qE '^GENAI_STUDIO_API_KEY=(sk-\.\.\.)?$' source/secret.env; then
  echo "ERROR: GENAI_STUDIO_API_KEY is present but empty/placeholder. Remove the line or set a real key."
  exit 1
fi
if grep -q '^ORALSCALE_ALLOW_TRANSCRIPT_SIDECAR=1' source/secret.env; then
  echo "ERROR: ORALSCALE_ALLOW_TRANSCRIPT_SIDECAR=1 must never ship to Gradescope —"
  echo "       it lets a student supply their own transcript (INV-INTEGRITY-8)."
  exit 1
fi

chmod 600 source/secret.env
chmod +x run_autograder
rm -f autograder.zip
# Gradescope extracts this zip INTO /autograder/source/, so the python files must
# sit at the TOP LEVEL of the archive — shipping our own source/ directory buried
# them at /autograder/source/source/ and the entry point could not find them.
#
# MODEL WEIGHTS ARE NEVER PACKAGED. setup.sh downloads the GGUF and the Whisper
# weights at IMAGE BUILD time, into source/models/, which is exactly where a
# developer running the grader locally also ends up with them. Zipping that
# directory put a 1.9 GB GGUF into every upload — the model shipped twice, once
# in the zip and once again on the image build, and a >1 GB upload is slow and
# fails silently on a poor connection. The zip is code + bank + secrets only.
( cd source && zip -r ../autograder.zip . \
    -x '__pycache__/*' '*.example' 'models/*' '*.gguf' '*.bin' '*.safetensors' '*.pt' >/dev/null )
zip autograder.zip setup.sh run_autograder >/dev/null
chmod 600 autograder.zip

# A zip this size means weights got in anyway. Refuse it rather than let an
# instructor spend twenty minutes uploading one, and refuse it HERE rather than
# in Gradescope, where the error would be a timeout with no cause attached.
ZIP_BYTES=$(wc -c < autograder.zip | tr -d ' ')
if [ "$ZIP_BYTES" -gt 104857600 ]; then
  echo "ERROR: autograder.zip is $((ZIP_BYTES / 1048576)) MB. Model weights belong in the"
  echo "  IMAGE (setup.sh downloads them at build time), never in the upload. Largest entries:"
  unzip -l autograder.zip | sort -rn | head -5
  exit 1
fi

# Read the pin BEFORE the ephemeral secret.env is deleted. This check used to run
# after the rm, so it always saw no file and always reported "not pinned" — on a
# zip that was pinned correctly.
PINNED="$(sed -n 's/^ORALSCALE_ASSIGNMENT=//p' source/secret.env 2>/dev/null | head -1)"

if [ "$EPHEMERAL" = "1" ]; then
  rm -f source/secret.env
  echo "Removed source/secret.env (it lives only inside the zip now)."
fi

# INV-DEPLOY-3: the pinned assignment is the ONLY thing consulted. Nothing is
# inferred from the Gradescope assignment's title — that guessing was removed in
# R15 precisely because renaming a Gradescope assignment could silently change
# which bank a submission was graded against. These two lines still described the
# old behaviour and told instructors one zip could serve every week; it cannot,
# and an unpinned one does not grade at all.
if [ -n "$PINNED" ]; then
  echo "Note: this zip grades '$PINNED' and nothing else. The Gradescope assignment's"
  echo "      title is not consulted, so you may title it whatever you like — but upload"
  echo "      this zip only to that assignment (INV-DEPLOY-3)."
else
  echo "WARNING: no ORALSCALE_ASSIGNMENT is pinned in this zip, so it does not say which"
  echo "         assignment it grades — and a zip that does not say WILL NOT GRADE. Build"
  echo "         through the packager, which writes one zip per assignment, named for it:"
  echo "           npm run package -- courses/<id>/course.json"
fi

echo
echo "Built autograder.zip — upload it in Gradescope (Programming Assignment > Configure Autograder)."
echo "It contains your secrets. Treat it like a password: no email, no shared drives, no git."
